"""Planning and running FFmpeg post-processing (merge, remux, audio conversion).

FFmpeg is only ever started through ``run_controlled`` from an argument list. Every input and
output path is generated by the application inside the job's own directory, never derived
from remote metadata.
"""

from __future__ import annotations

import logging
import re
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from ..core.errors import AppError, ErrorCode
from ..models.media import MediaFormat, MediaInfo
from ..utils.filenames import ALLOWED_OUTPUT_EXTENSIONS
from .ffmpeg_service import INSTALL_HINT, controlled_env, find_ffmpeg
from .process_utils import ProcessTimeout, run_controlled

logger = logging.getLogger("app.processing")

VIDEO_OUTPUTS = ("mp4", "mkv", "webm")
AUDIO_OUTPUTS = ("mp3", "m4a", "opus")
FFMPEG_TIMEOUT = 2 * 3600

_MP4_AUDIO = {"m4a", "mp4", "aac", "mp3"}
_WEBM_AUDIO = {"webm", "opus", "ogg"}
_OUT_TIME = re.compile(r"^out_time_(?:us|ms)=(\d+)$")

# Fallback re-encodes, used only when a lossless stream copy into the target container fails.
_VIDEO_TRANSCODE = {
    "mp4": ["-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-c:a", "aac", "-b:a", "192k"],
    "webm": ["-c:v", "libvpx-vp9", "-b:v", "0", "-crf", "32", "-deadline", "realtime", "-cpu-used", "8", "-c:a", "libopus"],
    "mkv": ["-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-c:a", "aac", "-b:a", "192k"],
}
_AUDIO_CODEC = {
    "mp3": ["-c:a", "libmp3lame", "-q:a", "2"],
    "m4a": ["-c:a", "aac", "-b:a", "192k"],
    "opus": ["-c:a", "libopus", "-b:a", "128k"],
}


@dataclass(frozen=True)
class ProcessingPlan:
    parts: tuple[MediaFormat, ...]  # formats to download, in order (video first, then audio)
    output_ext: str
    operation: str  # "none" | "remux" | "merge" | "convert_audio"
    expected_bytes: int  # sum of known part sizes (0 if unknown)

    @property
    def needs_processing(self) -> bool:
        return self.operation != "none"


def _bad_format(reason: str) -> AppError:
    return AppError(ErrorCode.FORMAT_NOT_AVAILABLE, "That output format isn't available for this download.", reason=reason)


def _best_audio(info: MediaInfo, target: str | None) -> MediaFormat | None:
    audio = [f for f in info.formats if f.type == "audio"]
    if not audio:
        return None
    preferred = {"mp4": _MP4_AUDIO, "mkv": _MP4_AUDIO | _WEBM_AUDIO, "webm": _WEBM_AUDIO}.get(target or "", set())
    pool = [f for f in audio if f.container in preferred] or audio
    return max(pool, key=lambda f: f.filesize or 0)


def plan_job(info: MediaInfo, fmt: MediaFormat, output_format: str | None) -> ProcessingPlan:
    """Decide what to download and produce. Raises FORMAT_NOT_AVAILABLE for impossible requests."""
    if output_format is not None:
        allowed = VIDEO_OUTPUTS if fmt.type == "video" else AUDIO_OUTPUTS
        if output_format not in allowed:
            raise _bad_format("output_not_allowed_for_type")

    if fmt.type == "audio":
        out = output_format or fmt.container
        if out not in ALLOWED_OUTPUT_EXTENSIONS:
            raise _bad_format("container_not_allowed")
        op = "none" if out == fmt.container else "convert_audio"
        return ProcessingPlan((fmt,), out, op, fmt.filesize or 0)

    if fmt.has_audio:
        out = output_format or fmt.container
        if out not in ALLOWED_OUTPUT_EXTENSIONS:
            raise _bad_format("container_not_allowed")
        return ProcessingPlan((fmt,), out, "none" if out == fmt.container else "remux", fmt.filesize or 0)

    audio = _best_audio(info, output_format or fmt.container)  # prefer audio that fits the video's own container
    if audio is None:  # nothing to merge with: deliver the video as it is
        out = output_format or fmt.container
        if out not in ALLOWED_OUTPUT_EXTENSIONS:
            raise _bad_format("container_not_allowed")
        return ProcessingPlan((fmt,), out, "none" if out == fmt.container else "remux", fmt.filesize or 0)
    if output_format:
        out = output_format
    elif fmt.container == "mp4" and audio.container in _MP4_AUDIO:
        out = "mp4"
    elif fmt.container == "webm" and audio.container in _WEBM_AUDIO:
        out = "webm"
    else:
        out = "mkv"
    return ProcessingPlan((fmt, audio), out, "merge", (fmt.filesize or 0) + (audio.filesize or 0))


# --------------------------------------------------------------------------- running


def _base_args(ffmpeg: str) -> list[str]:
    return [ffmpeg, "-hide_banner", "-nostdin", "-loglevel", "error", "-nostats", "-progress", "pipe:1", "-n"]


def build_command(ffmpeg: str, plan: ProcessingPlan, inputs: list[Path], output: Path, *, transcode: bool) -> list[str]:
    """The exact FFmpeg argument list. Paths are absolute and application-generated."""
    cmd = _base_args(ffmpeg)
    for path in inputs:
        cmd += ["-i", str(path)]

    if plan.operation == "convert_audio":
        cmd += ["-vn", "-map", "0:a:0", *_AUDIO_CODEC[plan.output_ext]]
    else:
        if plan.operation == "merge":
            cmd += ["-map", "0:v:0", "-map", "1:a:0"]
        else:
            cmd += ["-map", "0:v:0", "-map", "0:a:0?"]
        cmd += _VIDEO_TRANSCODE[plan.output_ext] if transcode else ["-c", "copy"]
        if plan.output_ext == "mp4":
            cmd += ["-movflags", "+faststart"]
    return [*cmd, str(output)]


def run_processing(
    plan: ProcessingPlan,
    inputs: list[Path],
    job_dir: Path,
    *,
    duration: int | None,
    cancel: threading.Event,
    on_fraction: Callable[[float], None],
    ffmpeg: str | None = None,
) -> Path:
    """Produce ``job_dir/out.<ext>`` from the downloaded parts and return it."""
    if not plan.needs_processing:
        raise ValueError("Nothing to process; the downloaded file is already the result.")
    ffmpeg = ffmpeg or find_ffmpeg()
    if not ffmpeg:
        raise AppError(ErrorCode.FFMPEG_NOT_FOUND, INSTALL_HINT, reason="ffmpeg_missing")
    output = job_dir / f"out.{plan.output_ext}"

    def on_line(line: str) -> None:
        match = _OUT_TIME.match(line)
        if match and duration:
            on_fraction(min(1.0, int(match.group(1)) / 1_000_000 / duration))

    attempts = [False] if plan.operation == "convert_audio" else [False, True]  # stream copy first, then re-encode
    last_tail: tuple[str, ...] = ()
    for transcode in attempts:
        if output.exists():
            output.unlink()
        try:
            result = run_controlled(
                build_command(ffmpeg, plan, inputs, output, transcode=transcode),
                env=controlled_env(ffmpeg), cancel=cancel, timeout=FFMPEG_TIMEOUT, on_line=on_line,
            )
        except ProcessTimeout:
            raise AppError(ErrorCode.TIMEOUT, "Processing took too long and was stopped.", reason="ffmpeg_timeout") from None
        except OSError:
            raise AppError(ErrorCode.FFMPEG_NOT_FOUND, INSTALL_HINT, reason="ffmpeg_spawn_failed") from None
        if result.returncode == 0 and output.is_file() and output.stat().st_size > 0:
            on_fraction(1.0)
            return output
        last_tail = result.tail
        logger.info("ffmpeg attempt failed", extra={"operation": "ffmpeg", "status": "retrying" if not transcode and len(attempts) > 1 else "failed"})

    logger.warning("processing failed", extra={"operation": "ffmpeg", "status": "failed", "reason": " | ".join(last_tail)[-300:]})
    if output.exists():
        output.unlink()
    raise AppError(ErrorCode.PROCESSING_FAILED, "The media couldn't be converted. The downloaded file may be damaged.", reason="ffmpeg_failed")
